"""Postmortem drafts. Numbers (impact, durations, timeline, action items) always come from the
incident record. A writer only adds the narrative: summary, contributing factors, and what
went well or poorly, each citing timeline entry ids. Citations are checked against the
timeline before the draft is saved, and every draft is marked as a draft for human editing.

Two writers share one interface: TemplateWriter (offline, deterministic, the default) and
ClaudeWriter (claude-opus-5-5, structured JSON output, client injected for tests).
"""

from __future__ import annotations

import json
import logging
from datetime import UTC, datetime
from typing import Any, Protocol

from incidentbot.logs import log
from incidentbot.models import Incident

logger = logging.getLogger("incidentbot.postmortem")

DRAFT_BANNER = ("DRAFT generated by incidentbot. Review every section, fill in the contributing "
                "factors, and remove this line before sharing.")
SKIP_KINDS = {"command", "reminder"}
MODEL = "claude-opus-5-5"

CITED_LIST = {
    "type": "array",
    "items": {
        "type": "object",
        "properties": {"text": {"type": "string"},
                       "citations": {"type": "array", "items": {"type": "string"}}},
        "required": ["text", "citations"],
        "additionalProperties": False,
    },
}
NARRATIVE_SCHEMA = {
    "type": "object",
    "properties": {
        "summary": {"type": "string"},
        "summary_citations": {"type": "array", "items": {"type": "string"}},
        "contributing_factors": CITED_LIST,
        "what_went_well": CITED_LIST,
        "what_went_poorly": CITED_LIST,
        "suggested_action_items": CITED_LIST,
    },
    "required": ["summary", "summary_citations", "contributing_factors", "what_went_well",
                 "what_went_poorly", "suggested_action_items"],
    "additionalProperties": False,
}
CITED_SECTIONS = ("contributing_factors", "what_went_well", "what_went_poorly",
                  "suggested_action_items")


def hhmm(ts: float) -> str:
    return datetime.fromtimestamp(ts, UTC).strftime("%H:%M")


def minutes(a: float | None, b: float | None) -> int | None:
    return None if a is None or b is None else round((b - a) / 60)


def build_facts(inc: Incident) -> dict[str, Any]:
    timeline = [{"id": e.id, "time": hhmm(e.ts), "ts": e.ts, "kind": e.kind, "actor": e.actor,
                 "text": e.text} for e in inc.sorted_timeline() if e.kind not in SKIP_KINDS]
    return {
        "incident_id": inc.id, "title": inc.title, "severity": inc.severity,
        "service": inc.service,
        "date": datetime.fromtimestamp(inc.detected_at, UTC).strftime("%Y-%m-%d"),
        "impact": {
            "detected": hhmm(inc.detected_at),
            "declared": hhmm(inc.declared_at),
            "mitigated": hhmm(inc.mitigated_at) if inc.mitigated_at else None,
            "resolved": hhmm(inc.resolved_at) if inc.resolved_at else None,
            "customer_impact_minutes": minutes(inc.detected_at,
                                               inc.mitigated_at or inc.resolved_at),
            "total_duration_minutes": minutes(inc.detected_at, inc.resolved_at),
            "time_to_acknowledge_minutes": minutes(inc.detected_at, inc.declared_at),
            "affected_users": inc.affected_users,
            "services": [inc.service],
        },
        "roles": dict(inc.roles),
        "timeline": timeline,
        "action_items": [{"id": a.id, "text": a.text, "owner": a.owner, "done": a.done,
                          "source_entry_id": a.source_entry_id} for a in inc.action_items],
    }


class PostmortemWriter(Protocol):
    name: str

    def write(self, facts: dict[str, Any]) -> dict[str, Any]:
        """Return the narrative: the keys of NARRATIVE_SCHEMA."""
        ...


def _first(facts, kind, contains: str = "") -> dict[str, Any] | None:
    return next((e for e in facts["timeline"] if e["kind"] == kind and contains in e["text"]),
                None)


class TemplateWriter:
    """Offline writer. Fills the narrative from the timeline with fixed templates."""

    name = "template"

    def write(self, facts: dict[str, Any]) -> dict[str, Any]:
        imp = facts["impact"]
        alert = _first(facts, "alert")
        declare = _first(facts, "declare")
        mitigation = next((e for e in facts["timeline"] if e["kind"] == "runbook"
                           and "applied" in e["text"]), None)
        monitoring = _first(facts, "state", "monitoring")
        cites = [e["id"] for e in (alert, declare, mitigation or monitoring) if e]
        how = ""
        if mitigation:
            run_id, _, result = mitigation["text"].partition(" ")
            how = f" Mitigation: {result.split('applied: ', 1)[-1]} ({run_id})."
        summary = (f"On {facts['date']}, {facts['severity']} {facts['incident_id']}: "
                   f"{facts['title'].lower()} on {facts['service']}. Customers were affected for "
                   f"{imp['customer_impact_minutes']} minutes and about "
                   f"{imp['affected_users']:,} users saw errors.{how}")
        factors: list[dict[str, Any]] = []
        deploy = _first(facts, "deploy")
        flag = _first(facts, "flag_change")
        if deploy and alert and deploy["ts"] <= alert["ts"]:
            gap = round((alert["ts"] - deploy["ts"]) / 60)
            factors.append({"text": f"{deploy['text']} at {deploy['time']}, {gap} minutes "
                                    "before the first alert. Confirm whether it caused the "
                                    "incident.", "citations": [deploy["id"], alert["id"]]})
        if flag:
            factors.append({"text": f"{flag['text']} at {flag['time']}. Check whether the "
                                    "flag change is related.", "citations": [flag["id"]]})
        factors.append({"text": "TODO: describe the technical cause in your own words.",
                        "citations": [alert["id"]] if alert else []})
        factors.append({"text": "TODO: what made detection or mitigation slower than it "
                                "could have been?", "citations": []})
        well, poorly = [], []
        tta = imp["time_to_acknowledge_minutes"]
        if declare and tta is not None:
            (well if tta <= 5 else poorly).append({
                "text": f"Incident declared {tta} minutes after the first signal.",
                "citations": [e for e in (alert and alert["id"], declare["id"]) if e]})
        reminders = facts.get("reminders_sent", 0)
        if reminders:
            poorly.append({"text": f"{reminders} update reminder(s) fired before the channel "
                                   "heard an update.", "citations": []})
        starred = [e for e in facts["timeline"] if e["kind"] == "message"]
        if starred:
            well.append({"text": "Key findings were starred in the channel and kept in the "
                                 "timeline.", "citations": [e["id"] for e in starred[:3]]})
        return {"summary": summary, "summary_citations": cites,
                "contributing_factors": factors, "what_went_well": well,
                "what_went_poorly": poorly, "suggested_action_items": []}


SYSTEM_PROMPT = """You draft blameless incident postmortems for an engineering team.
You get the facts of one resolved incident as JSON, including a timeline whose entries have
ids like T3. Write the narrative sections only. Rules:
- Use only facts in the JSON. Do not invent numbers, people, systems, or causes.
- Every item cites the timeline entry ids it relies on, using ids that appear in the timeline.
- Where the cause is not clear from the timeline, write a contributing factor that starts with
  "TODO:" and says what the team should find out.
- Blameless: describe systems and decisions, not individual fault.
- Keep each item to one or two sentences."""


class ClaudeWriter:
    """Claude writer. The anthropic SDK is imported only when no client is injected."""

    name = "claude"

    def __init__(self, client: Any = None, model: str = MODEL, max_tokens: int = 4000) -> None:
        if client is None:
            try:
                import anthropic
            except ImportError as exc:  # pragma: no cover - depends on install extras
                raise RuntimeError("Install the Claude extra first: uv sync --extra claude") \
                    from exc
            client = anthropic.Anthropic()
        self.client = client
        self.model = model
        self.max_tokens = max_tokens
        self.last_usage: dict[str, int] = {}

    def write(self, facts: dict[str, Any]) -> dict[str, Any]:
        resp = self.client.messages.create(
            model=self.model,
            max_tokens=self.max_tokens,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": "Incident facts:\n" + json.dumps(facts)}],
            output_config={"effort": "medium",
                           "format": {"type": "json_schema", "schema": NARRATIVE_SCHEMA}},
        )
        text = "".join(b.text for b in resp.content if getattr(b, "type", "") == "text")
        u = getattr(resp, "usage", None)
        if u is not None:
            self.last_usage = {"input_tokens": u.input_tokens, "output_tokens": u.output_tokens}
        return json.loads(text)


def validate_narrative(narr: Any, valid_ids: set[str]) -> list[str]:
    """Problems with a writer's output. Empty means the narrative is usable as is."""
    if not isinstance(narr, dict):
        return ["narrative is not a JSON object"]
    errors = [f"missing {k}" for k in NARRATIVE_SCHEMA["required"] if k not in narr]
    if errors:
        return errors
    if not isinstance(narr["summary"], str) or not narr["summary"].strip():
        errors.append("summary is empty")
    for cid in narr["summary_citations"]:
        if cid not in valid_ids:
            errors.append(f"summary cites unknown entry {cid}")
    for section in CITED_SECTIONS:
        for i, item in enumerate(narr[section]):
            if not isinstance(item, dict) or "text" not in item:
                errors.append(f"{section}[{i}] is malformed")
                continue
            for cid in item.get("citations", []):
                if cid not in valid_ids:
                    errors.append(f"{section}[{i}] cites unknown entry {cid}")
    return errors


def _clean(narr: dict[str, Any], valid_ids: set[str]) -> dict[str, Any]:
    """Drop citations to entries that do not exist. Items that relied only on bad citations
    are kept but flagged, so a human sees what the model claimed."""
    out = dict(narr)
    out["summary_citations"] = [c for c in narr["summary_citations"] if c in valid_ids]
    for section in CITED_SECTIONS:
        items = []
        for item in narr[section]:
            if not isinstance(item, dict) or "text" not in item:
                continue
            good = [c for c in item.get("citations", []) if c in valid_ids]
            flagged = bool(item.get("citations")) and not good
            items.append({"text": item["text"], "citations": good,
                          **({"unverified": True} if flagged else {})})
        out[section] = items
    return out


def generate(inc: Incident, writer: PostmortemWriter, ts: float) -> dict[str, Any]:
    facts = build_facts(inc)
    facts["reminders_sent"] = len(inc.reminders)
    valid = {e["id"] for e in facts["timeline"]}
    generator = writer.name
    try:
        narr = writer.write(facts)
        errors = validate_narrative(narr, valid)
    except Exception as exc:  # writer failures must never block resolving an incident
        log(logger, "postmortem writer failed", logging.WARNING, incident=inc.id,
            writer=writer.name, error=str(exc))
        narr, errors = None, [f"writer failed: {exc}"]
    structural = [e for e in errors if "cites unknown" not in e]
    if narr is None or structural:
        narr = TemplateWriter().write(facts)
        generator = f"template (fallback from {writer.name})"
    else:
        narr = _clean(narr, valid)
    return {
        "incident_id": inc.id, "title": inc.title, "status": "draft", "banner": DRAFT_BANNER,
        "generator": generator, "generated_at": ts, "citation_errors": errors,
        "severity": inc.severity, "service": inc.service, "date": facts["date"],
        "impact": facts["impact"], "roles": facts["roles"], "timeline": facts["timeline"],
        "action_items": facts["action_items"], **narr,
    }


def _cite(ids: list[str]) -> str:
    return f" [{', '.join(ids)}]" if ids else ""


def to_markdown(pm: dict[str, Any]) -> str:
    imp = pm["impact"]
    lines = [f"# Postmortem: {pm['incident_id']} {pm['title']}", "", f"> {pm['banner']}", "",
             f"Severity {pm['severity']}, service {pm['service']}, {pm['date']}. "
             f"Writer: {pm['generator']}.", "", "## Summary", "",
             pm["summary"] + _cite(pm["summary_citations"]), "", "## Impact", "",
             f"- Customer impact: {imp['customer_impact_minutes']} minutes "
             f"(detected {imp['detected']}, mitigated {imp['mitigated'] or 'n/a'})",
             f"- Total duration: {imp['total_duration_minutes']} minutes "
             f"(resolved {imp['resolved'] or 'n/a'})",
             f"- Time to acknowledge: {imp['time_to_acknowledge_minutes']} minutes",
             f"- Affected users: {imp['affected_users']:,}", "", "## Timeline (UTC)", ""]
    lines += [f"- {e['time']} [{e['id']}] {e['text']}" for e in pm["timeline"]]
    for title, key in (("Contributing factors", "contributing_factors"),
                       ("What went well", "what_went_well"),
                       ("What went poorly", "what_went_poorly")):
        lines += ["", f"## {title}", ""]
        lines += [f"- {i['text']}{_cite(i['citations'])}" for i in pm[key]] or ["- None noted."]
    lines += ["", "## Action items", ""]
    for a in pm["action_items"]:
        box = "x" if a["done"] else " "
        owner = f" (@{a['owner']})" if a["owner"] else ""
        lines.append(f"- [{box}] {a['id']}: {a['text']}{owner} [{a['source_entry_id']}]")
    for s in pm.get("suggested_action_items", []):
        lines.append(f"- [ ] Suggested: {s['text']}{_cite(s['citations'])}")
    if not pm["action_items"] and not pm.get("suggested_action_items"):
        lines.append("- None yet.")
    return "\n".join(lines) + "\n"
